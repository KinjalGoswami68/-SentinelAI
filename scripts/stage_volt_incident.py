"""
Stage the demo incident on Volt (decided 2026-11-11): Volt's fixture traffic is all
normal, so it never has an incident on its own. This posts 40 answers from the M10
upsell prompt (fixtures/m10/seed1_prompt_v2.jsonl, generated by gpt-oss-20b) to the
live /ingest as Volt with prompt_version "v2". The live service then does what it does
for any bot: version-regression check at 10 and 30 answers, incident, one
investigation (one Groq call), Slack messages (at most 3).

Run only inside 09:00-21:00 IST (Render may be asleep outside it). Idempotent:
request_id = volt-v2-<n>, so a re-run only sends what is missing.

  python scripts/stage_volt_incident.py          (key from volt_api_key.txt or VOLT_API_KEY)
"""
import json
import os
import sys
import time
from datetime import datetime, timedelta, timezone
from pathlib import Path

import requests

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import dev_truststore  # noqa: E402

dev_truststore.maybe_enable()
BASE = os.environ.get("BASE_URL", "https://sentinelai-qqph.onrender.com").rstrip("/")
N = 40
MODEL_LABEL = "volt-demo-fixture"     # same as demo_feed.py: only the prompt changes


def main():
    ist = datetime.now(timezone.utc) + timedelta(minutes=330)
    if not 9 <= ist.hour < 21:
        print(f"{ist:%H:%M} IST is outside 09:00-21:00; not posting")
        return 1
    key = os.environ.get("VOLT_API_KEY") or (ROOT / "volt_api_key.txt").read_text(encoding="utf-8").strip()
    rows = [json.loads(l) for l in open(ROOT / "fixtures/m10/seed1_prompt_v2.jsonl", encoding="utf-8") if l.strip()][:N]
    h = {"X-API-Key": key}
    for i, r in enumerate(rows):
        body = {"prompt": r["prompt"], "response": r["response"], "request_id": f"volt-v2-{i:03d}",
                "prompt_version": "v2", "model_version": MODEL_LABEL, "status": "ok"}
        for attempt in range(6):
            try:
                res = requests.post(f"{BASE}/ingest", headers=h, json=body, timeout=120)
            except requests.exceptions.RequestException as e:
                print(f"  {type(e).__name__}, retrying")
                time.sleep(5)
                continue
            if res.status_code == 503:
                time.sleep(int(res.headers.get("Retry-After", "5")))
                continue
            if res.status_code != 200:
                print(f"HTTP {res.status_code}: {res.text[:200]}")
                return 1
            d = res.json()
            if d.get("incident") or (i + 1) % 10 == 0:
                print(f"volt-v2-{i:03d}: {d.get('status')} distance={d.get('distance')} incident={d.get('incident')}")
            break
        else:
            print("ingest kept failing")
            return 1
    print(f"posted {N} answers as prompt_version v2")
    return 0


if __name__ == "__main__":
    sys.exit(main())
